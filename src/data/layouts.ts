/**
 * DEMONSTRATION APARTMENT LAYOUTS (floor-plan drawings)
 * ------------------------------------------------------
 * Fictional, original layouts created for the presentation version.
 * Replace / extend with the client's real architectural plans.
 *
 * Conventions (see src/lib/plan/types.ts):
 *  - metres; x → right, y ↓ down
 *  - main facade on top (y = 0), entrance on the bottom edge (y = h)
 *  - balconies at negative y
 *  - walls are generated automatically from the room rectangles
 */
import type { Furniture, Opening, Rect, Room, UnitLayout } from "@/lib/plan/types";

const R = (x: number, y: number, w: number, h: number): Rect => [x, y, w, h];
const room = (
  id: string,
  name: string,
  kind: Room["kind"],
  parts: Rect[],
  label?: [number, number],
): Room => ({ id, name, kind, parts, label });

const door = (
  o: "h" | "v",
  x: number,
  y: number,
  w: number,
  swing: 1 | -1,
  hinge: "start" | "end" = "start",
): Opening => ({ kind: "door", o, x, y, w, swing, hinge });
const entry = (o: "h" | "v", x: number, y: number, w: number, swing: 1 | -1): Opening => ({
  kind: "entry",
  o,
  x,
  y,
  w,
  swing,
  hinge: "start",
});
const win = (o: "h" | "v", x: number, y: number, w: number): Opening => ({ kind: "window", o, x, y, w });
const slider = (o: "h" | "v", x: number, y: number, w: number): Opening => ({ kind: "slider", o, x, y, w });
const pass = (o: "h" | "v", x: number, y: number, w: number): Opening => ({ kind: "passage", o, x, y, w });
const f = (
  t: Furniture["t"],
  x: number,
  y: number,
  w: number,
  h: number,
  rot: Furniture["rot"] = 0,
): Furniture => ({ t, x, y, w, h, rot });

